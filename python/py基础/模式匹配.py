score = 'B'

match score:
    case 'A':
        print('score is A.')
    case 'B':
        print('score is B.')
    case 'C':
        print('score is C.')
    case _: # _表示匹配到其他任何情况
        print('score is ???.')

#复杂匹配
#在上面这个示例中，第一个case x if x < 10表示当age < 10成立时匹配，且赋值给变量x
#第二个case 10仅匹配单个值，第三个case 11|12|...|18能匹配多个值，用|分隔。
age = 15

match age:
    #赋值给x
    case x if x < 10:
        print(f'< 10 years old: {x}')
    case 10:
        print('10 years old.')
    case 11 | 12 | 13 | 14 | 15 | 16 | 17 | 18:
        print('11~18 years old.')
    case 19:
        print('19 years old.')
    case _:
        print('not sure.')



